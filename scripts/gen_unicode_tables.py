"""Generate ``src/nl_shell/_unicode_tables.py`` from the Unicode Character Database (#144).

The character-safety policy (``nl_shell.render``, ``nl_shell.proposal``) reads every
Unicode property it uses from that generated module, never from the interpreter's
``unicodedata``, so the policy is the same on every supported Python. This script reads
the UCD text files (Ubuntu package ``unicode-data``, installed in ``/usr/share/unicode/``)
and writes only the ranges the policy needs:

- general categories Cf, Co, Cn (``UnicodeData.txt``; a code point not listed there is
  Cn) and Mn, Me (the combining marks);
- Default_Ignorable_Code_Point (``DerivedCoreProperties.txt``);
- White_Space (``PropList.txt``).

Usage::

    python3 scripts/gen_unicode_tables.py [--ucd /usr/share/unicode] [--expect 16.0.0]

The run fails if the UCD version is not ``--expect``, so a regenerated module never
silently changes the pinned version. The module is committed; the policy never runs this.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Iterable, Iterator
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "src" / "nl_shell" / "_unicode_tables.py"
MAX_CODE = 0x10FFFF
# The files whose first line carries the UCD version (UnicodeData.txt has no header).
VERSIONED = ("DerivedCoreProperties.txt", "PropList.txt")
HEADER = '''"""Unicode property tables for the character-safety policy (#144).

GENERATED by scripts/gen_unicode_tables.py from the Unicode Character Database {version};
do not edit by hand. Each table is a tuple of inclusive ``(first, last)`` code point
ranges, sorted and merged.
"""
'''


class VersionMismatch(SystemExit):
    """The UCD files are not the expected version."""


def data_lines(path: Path) -> Iterator[tuple[int, int, str]]:
    """``(first, last, value)`` per data line of a UCD ``range ; value`` file."""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        codes, value = (part.strip() for part in line.split(";", 1))
        first, _, last = codes.partition("..")
        yield int(first, 16), int(last or first, 16), value


def file_version(path: Path) -> str:
    """The version in the first line of a UCD file (``# PropList-16.0.0.txt``)."""
    with path.open(encoding="utf-8") as handle:
        first = handle.readline()
    match = re.search(r"-(\d+\.\d+\.\d+)\.txt", first)
    if match is None:
        raise VersionMismatch(f"{path}: no version in its first line: {first!r}")
    return match.group(1)


def check_version(ucd: Path, expect: str) -> None:
    """Refuse to generate from UCD files that are not version ``expect``."""
    found = {name: file_version(ucd / name) for name in VERSIONED}
    wrong = {name: v for name, v in found.items() if v != expect}
    if wrong:
        raise VersionMismatch(
            f"the UCD in {ucd} is not Unicode {expect}: "
            + ", ".join(f"{name} is {v}" for name, v in sorted(wrong.items()))
            + f". Install the {expect} files (Ubuntu package unicode-data) or pass "
            "--ucd with a directory that holds them."
        )


def general_categories(path: Path) -> list[str]:
    """The general category of every code point; ``Cn`` where UnicodeData has none."""
    cats = ["Cn"] * (MAX_CODE + 1)
    range_start: tuple[int, str] | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        code, name, cat = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            range_start = (code, cat)
            continue
        if name.endswith(", Last>"):
            if range_start is None or range_start[1] != cat:
                raise SystemExit(f"{path}: unmatched range end at {code:04X}")
            for c in range(range_start[0], code + 1):
                cats[c] = cat
            range_start = None
            continue
        cats[code] = cat
    return cats


def ranges(codes: Iterable[int]) -> list[tuple[int, int]]:
    """Sorted, merged ``(first, last)`` ranges covering ``codes``."""
    out: list[list[int]] = []
    for code in sorted(set(codes)):
        if out and out[-1][1] == code - 1:
            out[-1][1] = code
        else:
            out.append([code, code])
    return [(a, b) for a, b in out]


def property_codes(path: Path, name: str) -> set[int]:
    codes: set[int] = set()
    for first, last, value in data_lines(path):
        if value == name:
            codes.update(range(first, last + 1))
    return codes


def format_ranges(name: str, comment: str, rs: list[tuple[int, int]]) -> str:
    body = "".join(f"    (0x{a:04X}, 0x{b:04X}),\n" for a, b in rs)
    return f"# {comment}\n{name} = (\n{body})\n"


def generate(ucd: Path, expect: str) -> str:
    """The text of the tables module, from the UCD files in ``ucd``."""
    check_version(ucd, expect)
    cats = general_categories(ucd / "UnicodeData.txt")

    def category(*members: str) -> list[tuple[int, int]]:
        return ranges(c for c in range(MAX_CODE + 1) if cats[c] in members)

    ignorable = property_codes(
        ucd / "DerivedCoreProperties.txt", "Default_Ignorable_Code_Point"
    )
    white = property_codes(ucd / "PropList.txt", "White_Space")
    parts = [
        HEADER.format(version=expect),
        f'UNICODE_VERSION = "{expect}"\n',
        format_ranges("CF", "General_Category = Cf (format).", category("Cf")),
        format_ranges("CO", "General_Category = Co (private use).", category("Co")),
        format_ranges(
            "CN", "General_Category = Cn (unassigned, noncharacters).", category("Cn")
        ),
        format_ranges(
            "MARK", "General_Category = Mn or Me (combining marks).", category("Mn", "Me")
        ),
        format_ranges(
            "DEFAULT_IGNORABLE", "Default_Ignorable_Code_Point = Yes.", ranges(ignorable)
        ),
        format_ranges("WHITE_SPACE", "White_Space = Yes.", ranges(white)),
    ]
    return "\n\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, default=Path("/usr/share/unicode"))
    parser.add_argument("--expect", default="16.0.0")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    args.output.write_text(generate(args.ucd, args.expect), encoding="utf-8")
    print(f"wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
