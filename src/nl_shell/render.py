"""The character-safety policy: the one predicate and the one escape function (#143, #144).

Every text nl-shell prints from a proposal, from ``:context`` or from a start-up error goes
through ``escape`` (threat model, "Output rendering is filtered everywhere"), and the
proposal parser (``nl_shell.proposal``) rejects a ``command`` that ``has_hidden`` or
``too_many_marks`` flags, anywhere in it, quoted or not ("What the user confirms is
exactly what runs"). Both use the same predicate, so the character policy lives here and
nowhere else.

Every Unicode property the policy uses is read from the vendored tables in
``nl_shell._unicode_tables`` (Unicode 16.0.0, generated by
``scripts/gen_unicode_tables.py``), never from the interpreter's own Unicode database, so
the policy is the same on every supported Python.

Hidden (UTS #39 §3.1) means the set the properties define, plus a short named list of
known blank glyphs; a blank glyph on neither is not caught:

- C0 controls except LF and TAB, DEL, C1 controls, the bidi controls, U+2028 and U+2029,
  the tag block U+E0000-U+E007F and lone surrogates (#143);
- general category Cf (format), Co (private use) or Cn (unassigned in Unicode 16.0.0);
- Default_Ignorable_Code_Point (e.g. U+3164 HANGUL FILLER, U+034F, the variation
  selectors U+FE00-U+FE0F and U+E0100-U+E01EF);
- White_Space, except SPACE, LF and TAB (e.g. U+00A0, U+3000);
- ``BLANK_SYMBOLS``: U+2800 BRAILLE PATTERN BLANK, U+1D159 MUSICAL SYMBOL NULL NOTEHEAD,
  U+16FE4 KHITAN SMALL SCRIPT FILLER, U+13441 EGYPTIAN HIEROGLYPH FULL BLANK and U+13442
  EGYPTIAN HIEROGLYPH HALF BLANK, drawn blank but neither Default_Ignorable nor
  White_Space.

Combining marks (UTS #39 §5.4; general category Mn or Me): at most ``MAX_MARKS`` in a row,
counted over any run of marks whatever comes before it (a letter, nothing, LF or anything
else); any other character ends the run. ``escape`` writes the later marks of a run as
escapes; the parser rejects a ``command`` with a longer run.

This is not confusable or mixed-script detection: look-alike letters pass.

``escape`` writes a character as ``\\xHH`` (up to U+00FF), ``\\uHHHH`` (up to U+FFFF) or
``\\UHHHHHHHH``, in lowercase hex; everything else is unchanged, LF and TAB included.
With ``backslash=True`` (``:context``) a backslash is written as ``\\\\`` too, so a real
ESC (``\\x1b``) and the typed text ``\\x1b`` (``\\\\x1b``) print differently.
"""

from __future__ import annotations

from bisect import bisect_right
from collections.abc import Iterable, Iterator

from nl_shell import _unicode_tables as tables

UNICODE_VERSION = tables.UNICODE_VERSION

Ranges = tuple[tuple[int, int], ...]

CONTROLS: Ranges = ((0x00, 0x1F), (0x7F, 0x9F))
# The bidi controls: ALM, LRM, RLM, LRE..RLO, LRI..PDI (all Cf; listed for #143's set).
BIDI_CONTROLS: Ranges = (
    (0x061C, 0x061C),
    (0x200E, 0x200F),
    (0x202A, 0x202E),
    (0x2066, 0x2069),
)
LINE_AND_PARAGRAPH_SEPARATORS: Ranges = ((0x2028, 0x2029),)
TAG_BLOCK: Ranges = ((0xE0000, 0xE007F),)
SURROGATES: Ranges = ((0xD800, 0xDFFF),)
# Known blank glyphs that no Unicode property flags: BRAILLE PATTERN BLANK (So),
# EGYPTIAN HIEROGLYPH FULL BLANK and HALF BLANK (Lo), KHITAN SMALL SCRIPT FILLER (Mn),
# MUSICAL SYMBOL NULL NOTEHEAD (So).
BLANK_SYMBOLS: Ranges = (
    (0x2800, 0x2800),
    (0x13441, 0x13442),
    (0x16FE4, 0x16FE4),
    (0x1D159, 0x1D159),
)
# Shown as they are, although controls or White_Space.
VISIBLE = frozenset(map(ord, " \n\t"))
MAX_MARKS = 2


def _merge(*parts: Iterable[tuple[int, int]]) -> Ranges:
    """One sorted, disjoint range table covering every range in ``parts``."""
    out: list[list[int]] = []
    for first, last in sorted(r for part in parts for r in part):
        if out and first <= out[-1][1] + 1:
            out[-1][1] = max(out[-1][1], last)
        else:
            out.append([first, last])
    return tuple((first, last) for first, last in out)


def _without(ranges: Iterable[tuple[int, int]], codes: frozenset[int]) -> Iterator:
    """``ranges`` with the code points in ``codes`` cut out."""
    for first, last in ranges:
        start = first
        for code in sorted(c for c in codes if first <= c <= last):
            if start < code:
                yield (start, code - 1)
            start = code + 1
        if start <= last:
            yield (start, last)


class _Table:
    """Membership in sorted, disjoint ``(first, last)`` ranges, by binary search."""

    def __init__(self, ranges: Ranges) -> None:
        self._ranges = ranges
        self._starts = [first for first, _ in ranges]

    def __contains__(self, code: int) -> bool:
        index = bisect_right(self._starts, code) - 1
        return index >= 0 and code <= self._ranges[index][1]


_HIDDEN = _Table(
    _merge(
        _without(CONTROLS, VISIBLE),
        BIDI_CONTROLS,
        LINE_AND_PARAGRAPH_SEPARATORS,
        TAG_BLOCK,
        SURROGATES,
        tables.CF,
        tables.CO,
        tables.CN,
        tables.DEFAULT_IGNORABLE,
        _without(tables.WHITE_SPACE, VISIBLE),
        BLANK_SYMBOLS,
    )
)
_MARKS = _Table(tables.MARK)


def is_hidden(char: str) -> bool:
    """True when ``char`` (one code point) must not reach the screen as it is."""
    return ord(char) in _HIDDEN


def has_hidden(text: str) -> bool:
    """True when any character of ``text`` is hidden."""
    return any(is_hidden(char) for char in text)


def is_mark(char: str) -> bool:
    """True when ``char`` is a combining mark (general category Mn or Me)."""
    return ord(char) in _MARKS


def _mark_runs(text: str) -> Iterator[tuple[str, int]]:
    """Each character of ``text`` with its place in the current run of marks (0 if none)."""
    run = 0
    for char in text:
        run = run + 1 if is_mark(char) else 0
        yield char, run


def too_many_marks(text: str) -> bool:
    """True when ``text`` has more than ``MAX_MARKS`` combining marks in a row."""
    return any(run > MAX_MARKS for _, run in _mark_runs(text))


def escape_char(char: str) -> str:
    code = ord(char)
    if code <= 0xFF:
        return f"\\x{code:02x}"
    if code <= 0xFFFF:
        return f"\\u{code:04x}"
    return f"\\U{code:08x}"


def escape(text: str, *, backslash: bool = False) -> str:
    """``text`` with every hidden character, every combining mark past ``MAX_MARKS`` in a
    row, and (if asked) every backslash escaped."""
    out = []
    for char, run in _mark_runs(text):
        if backslash and char == "\\":
            out.append("\\\\")
        elif is_hidden(char) or run > MAX_MARKS:
            out.append(escape_char(char))
        else:
            out.append(char)
    return "".join(out)
